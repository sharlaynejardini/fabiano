import fs from 'node:fs/promises';
import crypto from 'node:crypto';
const base=new URL('.',import.meta.url);
let html=await fs.readFile(new URL('Index.html',base),'utf8');
const css=await fs.readFile(new URL('dashboard.css',base),'utf8');
const parts=await fs.readFile(new URL('dashboard.html',base),'utf8');
const js=await fs.readFile(new URL('dashboard.js',base),'utf8');
html=html.replace('</style>','\n'+css+'</style>');
const nav=parts.slice(0,parts.indexOf('</nav>')+6),sections=parts.slice(parts.indexOf('</nav>')+6);
html=html.replace('</header>','</header>'+nav).replace('<footer>',sections+'<footer>');
html=html.replace("['intro','quiz','finish','done']","['intro','quiz','finish','done','teacherLogin','dashboard']");
html=html.replace("function show(id){","function show(id){document.body.classList.toggle('admin',id==='dashboard');");
const start=html.indexOf('function submit(){'),end=html.indexOf('function makeId()',start);
if(start<0||end<0)throw Error('Não foi possível localizar o envio no HTML.');
html=html.slice(0,start)+html.slice(end);
html=html.replace('suas respostas serão salvas automaticamente na planilha Google do professor.','suas respostas serão registradas e ficarão disponíveis no painel do professor.');
html=html.replace('Seu professor poderá consultar a correção na planilha.','Seu professor poderá consultar a correção no painel.');
html=html.replace('</script>',js+'\n</script>');
await fs.writeFile(new URL('../index.html',base),html);
let backend=await fs.readFile(new URL('Codigo.gs',base),'utf8');
backend=backend.replace("hash_('agenor2026')","'"+crypto.createHash('sha256').update('agenor2026').digest('hex')+"'");
await fs.writeFile(new URL('Codigo.gs',base),backend);
console.log('index.html gerado na pasta Fabiano. A senha não está no HTML público.');
